export const MAP_SIGLA  = Object.fromEntries(SECRETARIAS.map(s => [s.sigla, s]));
export const MAP_NUMERO = Object.fromEntries(SECRETARIAS.map(s => [s.numero, s]));

export const getCor  = (sigla) => MAP_SIGLA[sigla]?.cor  ?? '#64748b';
export const getNome = (sigla) => MAP_SIGLA[sigla]?.nome ?? sigla;

export function getByNumero(numero) {
  return MAP_NUMERO[String(numero)] ?? null;
}

// Resolve nome completo do XLS → sigla (usado no processarXLS.js)
export function resolverSigla(nomeCompleto) {
  if (!nomeCompleto) return null;
  const upper = String(nomeCompleto).trim().toUpperCase();
  const found = SECRETARIAS.find(s =>
    s.sigla.toUpperCase() === upper ||
    s.nomesXLS.some(n => n.toUpperCase() === upper)
  );
  if (found) return found.sigla;
  return upper.split(' ').slice(0, 2).join(' ');
}

// Compatibilidade com folha/constants.js
export const MAPA_SECRETARIA = Object.fromEntries(
  SECRETARIAS.flatMap(s => s.nomesXLS.map(n => [n, s.sigla]))
);

// Compatibilidade com folha/constants.js e DashboardFolha
export const COR_SEC_FOLHA = Object.fromEntries(SECRETARIAS.map(s => [s.sigla, s.cor]));
// Também exporta com nome genérico
export const COR_SEC = COR_SEC_FOLHA;

// Compatibilidade com previas/constants.js
export function getNomeSecretaria(codigo) {
  const s = MAP_SIGLA[codigo];
  return s ? `${s.numero} - ${s.sigla}` : codigo;
}

export function getCorSecretaria(codigo) {
  return MAP_SIGLA[codigo]?.cor ?? '#64748b';
}
