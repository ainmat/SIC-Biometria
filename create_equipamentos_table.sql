-- Criar tabela de equipamentos
CREATE TABLE equipamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(255) NOT NULL,
  tipo VARCHAR(100) NOT NULL,
  localizacao VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('active', 'maintenance', 'inactive')),
  data_instalacao DATE NOT NULL,
  data_ultima_manutencao DATE,
  modelo VARCHAR(100),
  numero_serie VARCHAR(100) UNIQUE,
  descricao TEXT,
  secretaria VARCHAR(100),
  responsavel VARCHAR(100),
  fabricante VARCHAR(50) NOT NULL DEFAULT 'Outros',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Criar índices para melhor performance
CREATE INDEX idx_equipamentos_status ON equipamentos(status);
CREATE INDEX idx_equipamentos_tipo ON equipamentos(tipo);
CREATE INDEX idx_equipamentos_localizacao ON equipamentos(localizacao);
CREATE INDEX idx_equipamentos_secretaria ON equipamentos(secretaria);
CREATE INDEX idx_equipamentos_fabricante ON equipamentos(fabricante);

-- Criar trigger para atualizar o campo updated_at automaticamente
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ language 'plpgsql';

CREATE TRIGGER update_equipamentos_updated_at 
    BEFORE UPDATE ON equipamentos 
    FOR EACH ROW 
    EXECUTE FUNCTION update_updated_at_column();

