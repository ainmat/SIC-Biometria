-- Habilitar RLS (Row Level Security) para maior segurança
ALTER TABLE equipamentos ENABLE ROW LEVEL SECURITY;

-- Criar política para permitir leitura pública (se necessário)
CREATE POLICY "Equipamentos são visíveis para todos" ON equipamentos
  FOR SELECT USING (true);

-- Criar política para permitir inserções autenticadas
CREATE POLICY "Equipamentos podem ser inseridos por usuários autenticados" ON equipamentos
  FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- Criar política para permitir atualizações autenticadas
CREATE POLICY "Equipamentos podem ser atualizados por usuários autenticados" ON equipamentos
  FOR UPDATE USING (auth.role() = 'authenticated');

-- Criar política para permitir deleções autenticadas
CREATE POLICY "Equipamentos podem ser deletados por usuários autenticados" ON equipamentos
  FOR DELETE USING (auth.role() = 'authenticated');
